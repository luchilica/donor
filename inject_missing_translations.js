// Check if i18nCode already has some of these (avoid duplicates)
const entriesToAdd = [];
for (const [k, v] of Object.entries(translationMap)) {
  const escapedK = k.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
  const keyPattern = new RegExp(`"${escapedK}"\\s*:`);
  if (!keyPattern.test(i18nCode)) {
    entriesToAdd.push(`  "${k}": "${v}",`);
  }
}

if (entriesToAdd.length > 0) {
  const addition = entriesToAdd.join('\n') + '\n';
  // Insert right before the last closing brace };
  const lastBraceIdx = i18nCode.lastIndexOf('};');
  if (lastBraceIdx !== -1) {
    i18nCode = i18nCode.substring(0, lastBraceIdx) + addition + i18nCode.substring(lastBraceIdx);
    fs.writeFileSync(i18nPath, i18nCode, 'utf-8');
    console.log(`Successfully added ${entriesToAdd.length} missing translations to ${i18nPath}`);
  } else {
    console.error("Could not find ending }; in i18n.ts");
  }
} else {
  console.log("No translations need to be added.");
}
